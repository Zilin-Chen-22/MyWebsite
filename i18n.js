    "The perching interface used voltage-switchable electrorheological fluid, or VSERF. Under an electric field, suspended particles polarize and form chain-like structures, increasing the material's effective shear strength and interface friction. The compliant surface can conform to the target during contact, while electrical switching avoids the mass and mechanical complexity of claws, pumps, or transmissions.": "栖息界面采用电压可切换电流变液（VSERF）。在电场作用下，悬浮颗粒发生极化并形成链状结构，从而提高材料的等效剪切强度与界面摩擦力。柔顺表面能够在接触时适应目标形状，而电信号切换避免了抓爪、气泵或机械传动带来的质量与复杂度。",
